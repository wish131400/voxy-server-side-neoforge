use super::*;
use serde_json::json;

fn document() -> Value {
    let root=std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/worldgen");
    let read=|name:&str|serde_json::from_str::<Value>(&std::fs::read_to_string(root.join(name)).unwrap()).unwrap();
    let mut doc=read("overworld.json");
    for(k,f)in[("block_definitions","blocks.json"),("biomes","biomes.json"),
        ("grass_colormap","grass.json"),("foliage_colormap","foliage.json")] {doc[k]=read(f);}
    doc
}

fn block(name:&str)->Value { json!({"type":"minecraft:block","result_state":{"Name":name}}) }

#[test]
fn released_reference_codec_survives_server_dependencies_and_native_document() {
    let captured:Value=serde_json::from_str(include_str!("../../tests/fixtures/worldgen/surface-reference-snapshot.json")).unwrap();
    for (index,rule) in captured["rules"].as_array().unwrap().iter().enumerate() {
        let mut doc=document();
        for key in ["custom_registries","registry_tags"] {doc[key]=captured[key].clone();}
        doc["settings"]["surface_rule"]=json!({"type":"minecraft:sequence","sequence":[rule,block("minecraft:stone")]});
        let world=crate::backend::World::new(42,0,doc).unwrap();
        let row=world.surface_point(0,0).unwrap();
        assert_eq!(world.palette.states[row.values[4]as usize].name,
            match index {0=>"minecraft:granite",1|2=>"minecraft:dirt",_=>"minecraft:stone"});
    }
}

#[test]
fn released_bwg_rules_match_java_codec_and_bytecode_oracle() {
    // Generated by executing BWG 2.6.3's released classes and SurfaceSystemMixin.
    // Includes 16x16 weighted choices, signed coordinates, f32 noise scaling,
    // legacy/xoroshiro factories, constant/uniform providers and length-1 bands.
    let rows:Value=serde_json::from_str(include_str!("../../tests/fixtures/worldgen/bwg-surface-oracle.json")).unwrap();
    for row in rows.as_array().unwrap() {
        let mut doc=document();doc["settings"]["surface_rule"]=row["rule"].clone();
        doc["settings"]["legacy_random_source"]=row["legacy"].clone();
        let mut terrain=Terrain::from_document(row["seed"].as_i64().unwrap(),&doc).unwrap();
        let mut palette=Palette::from_json(&doc["block_definitions"]).unwrap();
        let surface=Surface::new(&mut terrain,&doc,&mut palette).unwrap();
        for sample in row["samples"].as_array().unwrap() {
            let p=[sample[0].as_i64().unwrap()as i32,sample[1].as_i64().unwrap()as i32,sample[2].as_i64().unwrap()as i32];
            let context=Context {p,biome:"minecraft:plains",cold:false,steep:false,depth:3,
                secondary:0.,above:1,below:10,water:i32::MIN,min_surface:-64};
            let actual=surface.rule(&surface.rule,&terrain.graph,&context);
            let expected=sample[3].as_str().map(|name|palette.named(name).unwrap());
            assert_eq!(actual,expected,"seed={} legacy={} rule={} p={p:?}",row["seed"],row["legacy"],row["rule"]);
        }
    }
}

#[test]
fn surface_references_preserve_order_empty_fallthrough_and_tag_members() {
    let mut doc=document();
    let absent=json!({"type":"minecraft:condition","if_true":{"type":"minecraft:biome","biome_is":["other:biome"]},"then_run":block("minecraft:air")});
    doc["custom_registries"]=json!({"lithostitched:surface_rule":{"test:none":absent,"test:first":block("minecraft:granite"),"test:last":block("minecraft:dirt")}});
    doc["registry_tags"]=json!({"lithostitched:surface_rule":{"test:ordered":["test:none","test:first","test:last"],"test:empty":[]}});
    for refs in [json!("test:first"),json!(["test:none","test:first","test:last"]),json!("#test:ordered"),json!([absent.clone(),block("minecraft:granite")])] {
        doc["settings"]["surface_rule"]=json!({"type":"minecraft:sequence","sequence":[{"type":"lithostitched:reference","rules":refs},block("minecraft:dirt")]});
        let world=crate::backend::World::new(42,0,doc.clone()).unwrap();
        for row in world.surface_points(&[(-17,-31),(0,0),(1537,-2049)]).unwrap() {
            assert_eq!(world.palette.states[row.values[4]as usize].name,"minecraft:granite");
        }
    }
    for refs in [json!([]),json!("#test:empty")] {
        doc["settings"]["surface_rule"]=json!({"type":"minecraft:sequence","sequence":[{"type":"lithostitched:reference","rules":refs},block("minecraft:dirt")]});
        let world=crate::backend::World::new(42,0,doc.clone()).unwrap();
        let row=world.surface_point(0,0).unwrap();
        assert_eq!(world.palette.states[row.values[4]as usize].name,"minecraft:dirt");
    }
    for refs in [json!("test:missing"),json!("#test:missing")] {
        doc["settings"]["surface_rule"]=json!({"type":"lithostitched:reference","rules":refs});
        assert!(crate::backend::World::new(42,0,doc.clone()).is_err());
    }
    doc["custom_registries"]["lithostitched:surface_rule"]["test:cycle"]=json!({"type":"lithostitched:reference","rules":"test:cycle"});
    doc["settings"]["surface_rule"]=json!({"type":"lithostitched:reference","rules":"test:cycle"});
    assert!(crate::backend::World::new(42,0,doc).is_err());
}

#[test]
fn weighted_rules_keep_cold_secondary_and_biome_predicates_on_full_path() {
    let mut doc=document();
    doc["settings"]["surface_rule"]=json!({"type":"minecraft:sequence","sequence":[
        {"type":"biomeswevegone:state_provider","provider":[{"weight":1,"data":{
            "type":"minecraft:condition","if_true":{"type":"minecraft:temperature"},"then_run":block("minecraft:snow_block")}}]},
        block("minecraft:granite")]});
    let mut terrain=Terrain::from_document(42,&doc).unwrap();
    let mut palette=Palette::from_json(&doc["block_definitions"]).unwrap();
    let surface=Surface::new(&mut terrain,&doc,&mut palette).unwrap();
    for cold in [true,false] {
        let context=Context {p:[-17,90,31],biome:"minecraft:plains",cold,steep:false,depth:3,
            secondary:0.,above:1,below:10,water:i32::MIN,min_surface:-64};
        assert_eq!(surface.rule(&surface.rule,&terrain.graph,&context),Some(palette.named(if cold{"minecraft:snow_block"}else{"minecraft:granite"}).unwrap()));
    }
}
