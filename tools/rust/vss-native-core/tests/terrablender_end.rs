use serde_json::{json, Value};
use vss_native_core::{climate::BiomeSource, density::{Graph, Mode}};

fn area(biome: &str) -> Value {
    json!({"size":2,"default_biome":"minecraft:ocean","biomes":[{"biome":biome,"weight":7}]})
}
fn document(erosion: Value) -> Value {
    json!({"settings":{"legacy_random_source":true,"noise_router":{"erosion":erosion}},
        "biome_source":{"type":"minecraft:the_end"},
        "vss_terrablender_end":{"revision":1,"seed":42,"density_coordinates":"block",
            "highlands":area("test:highlands"),"midlands":area("test:midlands"),
            "edge":area("test:edge"),"islands":area("test:islands")}})
}
#[test]
fn end_thresholds_center_and_wrapping_match_the_java_contract() {
    for (erosion, expected) in [(0.2500001,"test:highlands"),(0.25,"test:midlands"),
        (-0.0625,"test:midlands"),(-0.0625001,"test:edge"),(-0.21875,"test:edge"),(-0.2187501,"test:islands")] {
        let doc = document(json!(erosion)); let graph = Graph::from_document(42,&doc).unwrap();
        let source = BiomeSource::from_document(&doc,&graph,42).unwrap();
        assert!(source.uses_terrablender_routing());
        let mut scratch = graph.scratch(0,0,4,8).unwrap(); let mut last = None;
        assert_eq!(source.sample(&graph,[260,17,0],&mut scratch,&mut last),expected);
        assert_eq!(source.sample(&graph,[256,17,0],&mut scratch,&mut last),"minecraft:the_end");
        assert_eq!(source.sample(&graph,[-257,17,0],&mut scratch,&mut last),expected);
        for n in [i32::MIN,i32::MAX] { assert_eq!(source.sample(&graph,[n,17,n],&mut scratch,&mut last),"minecraft:the_end"); }
    }
}
#[test]
fn exact_block_erosion_coordinates_are_used_instead_of_chunk_centers() {
    let doc = document(json!({"type":"minecraft:end_islands"}));
    let graph = Graph::from_document(42,&doc).unwrap(); let erosion = graph.root("erosion").unwrap();
    let source = BiomeSource::from_document(&doc,&graph,42).unwrap();
    let mut scratch = graph.scratch(0,0,4,8).unwrap(); let mut last = None; let mut differences = 0;
    let classify = |v:f64| if v>0.25 {"test:highlands"} else if v>=-0.0625 {"test:midlands"}
        else if v< -0.21875 {"test:islands"} else {"test:edge"};
    for z in (-1024..=1024).step_by(23) { for x in (-1024..=1024).step_by(19) {
        let p = [x*4,0,z*4];
        let cx = p[0]>>4; let cz = p[2]>>4;
        if cx as i64*cx as i64 + cz as i64*cz as i64 <= 4096 { continue; }
        let expected = classify(graph.compute(erosion,p,Mode::Raw,&mut scratch));
        let vanilla = classify(graph.compute(erosion,[(cx*2+1)*8,0,(cz*2+1)*8],Mode::Raw,&mut scratch));
        differences += usize::from(expected!=vanilla);
        assert_eq!(source.sample(&graph,[x,0,z],&mut scratch,&mut last),expected);
    }}
    assert!(differences>100,"fixture must detect a regression to chunk-centered vanilla End sampling");
}
#[test]
fn weighted_area_duplicates_match_the_independent_java_grid_fixture() {
    let mut doc = document(json!(1));
    doc["vss_terrablender_end"]["highlands"]["biomes"] = json!([
        {"biome":"test:a","weight":10},{"biome":"test:b","weight":100},{"biome":"test:a","weight":100}]);
    let graph = Graph::from_document(42,&doc).unwrap(); let source = BiomeSource::from_document(&doc,&graph,42).unwrap();
    let mut scratch = graph.scratch(0,0,4,8).unwrap(); let mut last = None; let mut actual=String::new();
    for z in (768..=1280).step_by(64) { for x in (-256..=256).step_by(64) {
        actual.push(if source.sample(&graph,[x,0,z],&mut scratch,&mut last)=="test:a" {'0'}else{'1'});
    } actual.push(' '); }
    // Generated by shared Java TerraBlenderGrid (seed42,size2,rawID entries0/1/0,weights10/100/100).
    assert_eq!(actual.trim(),"010001100 000001100 010011110 000001010 110110100 010010100 011110100 111100010 010100110");
}
#[test]
fn zero_weight_and_empty_area_use_the_released_ocean_fallback() {
    for entries in [json!([]),json!([{"biome":"test:unused","weight":0}])] {
        let mut doc=document(json!(1)); doc["vss_terrablender_end"]["highlands"]["biomes"]=entries;
        let graph=Graph::from_document(42,&doc).unwrap(); let source=BiomeSource::from_document(&doc,&graph,42).unwrap();
        let mut scratch=graph.scratch(0,0,4,8).unwrap(); let mut last=None;
        assert_eq!(source.sample(&graph,[1024,0,-1024],&mut scratch,&mut last),"minecraft:ocean");
    }
}
#[test]
fn malformed_required_routes_are_rejected() {
    let original=document(json!(1)); let graph=Graph::from_document(42,&original).unwrap();
    for (field,value) in [("revision",json!(2)),("seed",json!(41)),("density_coordinates",json!("chunk_center"))] {
        let mut doc=original.clone(); doc["vss_terrablender_end"][field]=value;
        assert!(BiomeSource::from_document(&doc,&graph,42).is_err());
    }
    for size in [-1,33] { let mut doc=original.clone(); doc["vss_terrablender_end"]["edge"]["size"]=json!(size);
        assert!(BiomeSource::from_document(&doc,&graph,42).is_err()); }
    for weight in [-1i64,2147483648,4294967296] { let mut doc=original.clone();
        doc["vss_terrablender_end"]["edge"]["biomes"][0]["weight"]=json!(weight);
        assert!(BiomeSource::from_document(&doc,&graph,42).is_err()); }
    let mut doc=original.clone(); doc["biome_source"]["type"]=json!("minecraft:fixed");
    assert!(BiomeSource::from_document(&doc,&graph,42).is_err());
}
